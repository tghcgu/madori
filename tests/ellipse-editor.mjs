import assert from 'node:assert/strict';

export async function verifyEllipses({page,importPlan,choose,planPoint,change,move,pixels,output}) {
  const plan=entities=>({floors:[{id:'f1',name:'1F',entities}],activeFloor:0,roofs:[],selectedId:null});
  const snapshot=()=>page.evaluate(()=>window.__editorTest.snapshot());
  const entity=async id=>(await snapshot()).floors[0].entities.find(e=>e.id===id);
  const click=async(x,y)=>{const p=await planPoint(x,y);await page.mouse.click(p.x,p.y);};
  await importPlan(plan([{id:'circle',type:'shape',kind:'circle',x:400,y:400,r:200,startAngle:0,endAngle:Math.PI*2}]));
  await page.locator('button[data-view-mode="split"]').click();
  await click(600,400);
  await change('#shapeWInput',600);
  let e=await entity('circle'); assert.equal(e.kind,'ellipse');assert.equal(e.r,300);assert.equal(e.ry,200);
  assert.deepEqual([e.x,e.y],[400,400]);
  await change('#shapeHInput',240);assert.equal((await entity('circle')).ry,120);
  await page.locator('#fitButton').click();
  await move(await planPoint(700,400),-35,0);
  e=await entity('circle');assert.ok(e.r<300);assert.equal(e.ry,120);
  await page.locator('#undoButton').click();
  await move(await planPoint(400,520),0,35);
  e=await entity('circle');assert.equal(e.r,300);assert.ok(e.ry>120);
  await page.locator('#undoButton').click();
  await move(await planPoint(700,400),-35,0,true);
  e=await entity('circle');assert.equal(e.r,300);assert.equal(e.ry,120);
  const bounds=await page.evaluate(()=>window.__editorTest.bounds('circle'));
  assert.ok(Math.abs(bounds.max[0]-bounds.min[0]-6)<.2);
  assert.ok(Math.abs(bounds.max[2]-bounds.min[2]-2.4)<.2);
  assert.equal(await page.evaluate(()=>window.__editorTest.hit(400,520)),'circle');
  assert.equal(await page.evaluate(()=>window.__editorTest.hit(400,700)),null);
  await page.keyboard.press('r');
  e=await entity('circle');assert.equal(e.r,120);assert.equal(e.ry,300);
  await page.locator('#undoButton').click();
  await page.locator('#shapeFloorButton').click();
  let floor=(await snapshot()).floors[0].entities.find(e=>e.type==='room');
  assert.equal(floor.w,600);assert.equal(floor.h,240);
  assert.equal(await page.evaluate(id=>window.__editorTest.floorAt(id,690,510),floor.id),false);
  assert.equal(await page.locator('[data-floor-preset="ellipse"]').getAttribute('aria-pressed'),'true');
  await move(await planPoint(floor.x+floor.w,floor.y+floor.h/2),-25,0);
  floor=await entity(floor.id);assert.equal(floor.h,240);assert.ok(floor.w<600);
  assert.deepEqual([floor.x+floor.w/2,floor.y+floor.h/2],[400,400]);
  await page.locator('[data-floor-preset="circle"]').click();
  floor=await entity(floor.id);assert.equal(floor.w,floor.h);
  await page.locator('[data-floor-preset="ellipse"]').click();
  floor=await entity(floor.id);assert.notEqual(floor.w,floor.h);
  await choose('[data-roof-add="dome"]');
  const roof=(await snapshot()).roofs[0];
  assert.equal(roof.w,floor.w+80);assert.equal(roof.h,floor.h+80);
  await change('#roofWInput',600);await change('#roofHInput',300);
  assert.equal((await snapshot()).roofs[0].w,600);assert.equal((await snapshot()).roofs[0].h,300);
  await page.locator('#fitButton').click();
  await page.screenshot({path:`${output}/ellipse-desktop.png`});
  const stored=await snapshot();
  for (const floor of stored.floors) for (const e of floor.entities) e.locked ??= false;
  await page.reload({waitUntil:'domcontentloaded'});await page.waitForFunction(()=>Boolean(window.__editorTest));
  assert.deepEqual((await snapshot()).floors,stored.floors);assert.deepEqual((await snapshot()).roofs,stored.roofs);
  await importPlan(plan([{id:'extent',type:'room',name:'',x:0,y:0,w:800,h:600,color:'#ffffff'}]));
  await page.locator('button[data-view-mode="plan"]').click();
  await choose('[data-shape="ellipse"]');
  const p=await planPoint(100,100),q=await planPoint(700,300);
  await move(p,q.x-p.x,q.y-p.y);
  e=(await snapshot()).floors[0].entities.find(e=>e.kind==='ellipse');
  assert.ok(e);assert.equal(e.r,300);assert.equal(e.ry,100);
  await page.locator('[data-tool="select"]').click();await click(700,200);
  await page.locator('#entityLockedInput').check();assert.equal(await page.locator('#shapeWInput').isDisabled(),true);
  await page.locator('#entityLockedInput').uncheck();
  await page.locator('#shapeKindInput').selectOption('circle');assert.equal((await entity(e.id)).ry,undefined);
  await page.locator('#shapeKindInput').selectOption('ellipse');assert.equal((await entity(e.id)).ry,180);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#panelToggle').click();
  await page.locator('#fitButton').click();
  await page.locator('button[data-view-mode="three"]').click();
  assert.ok((await pixels()).colors>20);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:`${output}/ellipse-mobile.png`});
  console.log('PASS: ellipse drawing, circle conversion, independent axis handles, centered floors/roofs, 2D and 3D, rotation, lock, undo, cancellation and reload');
}
