import assert from 'node:assert/strict';

export async function verifyThreeSelection({ page, importPlan, project, planPoint, move, pixels, output }) {
  const table = { id: 'table', type: 'furniture', kind: 'table', x: 120, y: 180, w: 160, h: 85, rotation: 0 };
  const second = { ...table, id: 'second', x: 420 };
  const floor = { id: 'floor', type: 'room', name: '', x: 0, y: 0, w: 800, h: 600, color: '#c9ae7c', surface: 'wood' };
  const plan = { floors: [{ id: 'f1', name: '1F', entities: [floor, table, second] }], activeFloor: 0, selectedId: null, roofs: [] };
  const snapshot = () => page.evaluate(() => window.__editorTest.snapshot());
  const ids = () => page.evaluate(() => window.__editorTest.selection());
  const point = (item = table, height = .42) => project(item.x + item.w / 2, item.y + item.h / 2, height);
  const click = async (p, twice = false) => twice ? page.mouse.dblclick(p.x, p.y) : page.mouse.click(p.x, p.y);
  const refit = async () => {
    await page.locator('[data-view-mode="split"]').click();
    await page.locator('[data-view-mode="three"]').click();
    await page.waitForTimeout(400);
  };
  await importPlan(plan);
  await page.locator('[data-view-mode="three"]').click();
  await page.locator('[data-tool="select"]').click();
  await page.waitForTimeout(400);
  await click(await point());
  assert.deepEqual(await ids(), [], 'single click does not select furniture');
  assert.equal(await page.locator('#furnitureWInput').count(), 0);
  const held = await point();
  await page.mouse.move(held.x, held.y); await page.mouse.down();
  await page.waitForTimeout(650); await page.mouse.up();
  assert.deepEqual(await ids(), [], 'holding does not select furniture');
  const before = await snapshot(), orbit = await pixels();
  await move(await point(), 55, 20);
  assert.deepEqual(await ids(), []);
  assert.deepEqual((await snapshot()).floors, before.floors, 'orbit does not edit furniture');
  assert.notEqual((await pixels()).hash, orbit.hash);
  await refit();
  await click(await point(), true);
  assert.deepEqual(await ids(), ['table']);
  assert.equal(await page.locator('#furnitureWInput').inputValue(), '160');
  assert.equal(await page.locator('#threeMoveToggle').getAttribute('aria-pressed'), 'true');
  await click(await point(second));
  assert.deepEqual(await ids(), ['table'], 'single click on another piece preserves selection');
  await click(await point(second), true);
  assert.deepEqual(await ids(), ['second']);
  await move(await point(second), 50, 20);
  assert.notDeepEqual((await snapshot()).floors, before.floors);
  await page.locator('#undoButton').click();
  assert.deepEqual((await snapshot()).floors, before.floors);
  await page.keyboard.press('Escape');
  await page.locator('[data-tool="wall"]').click();
  await click(await point(), true);
  assert.deepEqual(await ids(), ['table'], 'double click selects from a drawing tool');
  assert.equal(await page.locator('[data-tool="select"]').getAttribute('aria-pressed'), 'true');
  await page.locator('#entityLockedInput').check();
  await page.keyboard.press('Escape');
  await click(await point());
  assert.deepEqual(await ids(), []);
  await click(await point(), true);
  assert.deepEqual(await ids(), ['table'], 'locked furniture can still be selected to unlock it');
  assert.equal(await page.locator('#entityLockedInput').isChecked(), true);
  assert.equal(await page.locator('#threeMoveToggle').isDisabled(), true);
  assert.equal(await page.locator('#threeMoveToggle').getAttribute('aria-pressed'), 'false');
  const locked = await snapshot();
  await move(await point(), 45, 20);
  assert.deepEqual((await snapshot()).floors, locked.floors);
  await refit();
  await page.locator('#entityLockedInput').uncheck();
  await page.keyboard.down('Control'); await click(await point(second)); await page.keyboard.up('Control');
  assert.deepEqual((await ids()).sort(), ['second', 'table']);
  await click(await point(), true);
  assert.deepEqual((await ids()).sort(), ['second', 'table'], 'double click preserves a selected group');
  await page.screenshot({ path: `${output}/three-double-selection-desktop.png` });
  await page.keyboard.press('Escape');
  await page.locator('[data-view-mode="plan"]').click();
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await click(await planPoint(200, 220));
  assert.deepEqual(await ids(), ['table'], '2D still selects with one click');

  const upper = { ...table, id: 'upper-table' };
  await importPlan({ ...plan, floors: [plan.floors[0], { id: 'f2', name: '2F', entities: [{ ...floor, id: 'upper-floor' }, upper] }] });
  await page.locator('[data-view-mode="three"]').click();
  await page.waitForTimeout(400);
  await click(await point(upper, 3.17));
  assert.equal((await snapshot()).activeFloor, 0, 'single click does not switch floors');
  assert.deepEqual(await ids(), []);
  await click(await point(upper, 3.17), true);
  assert.equal((await snapshot()).activeFloor, 1);
  assert.deepEqual(await ids(), ['upper-table']);
  assert.equal(await page.locator('#furnitureWInput').inputValue(), '160');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#panelToggle').click();
  await refit();
  await page.keyboard.press('Escape');
  await click(await point(upper, 3.17));
  assert.deepEqual(await ids(), []);
  await click(await point(upper, 3.17), true);
  assert.deepEqual(await ids(), ['upper-table']);
  assert.ok((await pixels()).colors > 20);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${output}/three-double-selection-mobile.png` });
  console.log('PASS: 3D double-click selection, no single-click/hold selection, orbit, editing, locks, groups, upper floors, 2D clicks and mobile layout');
}
