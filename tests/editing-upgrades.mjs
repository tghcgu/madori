import assert from 'node:assert/strict';

export async function verifyEditingUpgrades({ page, importPlan, planPoint, project, move, change, output }) {
  const room = { id: 'floor', type: 'room', name: '主寝室', x: 0, y: 0, w: 600, h: 500, surface: 'wood', color: '#c9ae7c' };
  const text = { id: 'text', type: 'text', text: 'ホール\n入口', x: 800, y: 200, size: 30, rotation: 0 };
  const plan = entities => ({ floors: [{ id: 'f1', name: '1F', entities }], activeFloor: 0, selectedId: null, roofs: [] });
  const snapshot = () => page.evaluate(() => window.__editorTest.snapshot());
  const item = async id => (await snapshot()).floors.flatMap(f => f.entities).find(e => e.id === id);
  const click = async (x, y) => { const p = await planPoint(x, y); await page.mouse.click(p.x, p.y); };
  await page.locator('button[data-view-mode="split"]').click();
  await importPlan(plan([room, text]));
  await page.locator('[data-tool="select"]').click();
  await click(300, 300);
  await change('#roomLabelSizeInput', 36);
  await page.locator('[data-writing-mode="vertical"]').click();
  assert.equal((await item('floor')).labelSize, 36);
  assert.equal((await item('floor')).writingMode, 'vertical');
  const label = await page.evaluate(() => window.__editorTest.roomLabelBounds('floor'));
  assert.ok(label.h > 108, 'selection includes the entire vertical room label');
  const labelPoint = await planPoint(25, 70);
  await move(labelPoint, 35, 20);
  assert.notEqual((await item('floor')).labelOffsetX ?? 10, 10);
  assert.equal((await item('floor')).x, 0, 'moving vertical text does not move the room');
  await click(800, 200);
  await page.locator('[data-writing-mode="vertical"]').click();
  await change('#textSizeInput', 40);
  const bounds = await page.evaluate(() => window.__editorTest.textBounds('text'));
  assert.equal(bounds.w, 100); assert.equal(bounds.h, 120);
  await page.locator('#undoButton').click();
  assert.equal((await item('text')).size, 30);
  await page.locator('#redoButton').click();
  await page.reload();
  await page.waitForFunction(() => Boolean(window.__editorTest));
  assert.equal((await item('text')).writingMode, 'vertical');
  assert.equal((await item('floor')).labelSize, 36);
  await page.screenshot({ path: `${output}/vertical-labels.png` });
  await page.locator('#imageExportButton').click();
  const pending = page.waitForEvent('download');
  await page.locator('#imageExportPlan').click();
  await (await pending).saveAs(`${output}/vertical-labels-export.png`);
  console.log('PASS: room label size, vertical room/free text, multiline bounds, drag, undo, reload and PNG');

  await importPlan(plan([{ ...room, name: '' }]));
  await click(100, 100);
  await page.locator('#roomShapeInput').selectOption('l');
  assert.equal((await item('floor')).outline.length, 6);
  assert.equal(await page.evaluate(() => window.__editorTest.hit(500, 450)), null, 'the cutout is not selectable floor');
  assert.equal(await page.evaluate(() => window.__editorTest.floorAt('floor', 500, 450)), false, '3D has the same cutout');
  assert.equal(await page.evaluate(() => window.__editorTest.floorAt('floor', 100, 450)), true);
  const corner = await planPoint(300, 250);
  await move(corner, -25, 0);
  const changed = await item('floor');
  assert.notEqual(changed.outline[3][0], .5, 'corners can be dragged');
  await page.locator('#undoButton').click();
  assert.equal((await item('floor')).outline[3][0], .5);
  await page.locator('#floorVertexAdd').click();
  assert.equal((await item('floor')).outline.length, 7);
  await page.locator('#floorVertexRemove').click();
  assert.equal((await item('floor')).outline.length, 6);
  await page.locator('#entityLockedInput').check();
  assert.equal(await page.locator('#roomShapeInput').isDisabled(), true);
  assert.equal(await page.locator('#floorVertexAdd').isDisabled(), true);
  await page.locator('#entityLockedInput').uncheck();
  await page.locator('#roomShapeInput').selectOption('circle');
  assert.equal((await item('floor')).outline.length, 64);
  assert.equal(await page.evaluate(() => window.__editorTest.floorAt('floor', 10, 10)), false);
  await page.reload();
  await page.waitForFunction(() => Boolean(window.__editorTest));
  assert.equal((await item('floor')).outline.length, 64);
  const shape = { id: 'shape', type: 'shape', kind: 'polygon', x: 300, y: 250, r: 200, sides: 6, rotation: 0, startAngle: 0, endAngle: Math.PI * 2 };
  await importPlan(plan([shape]));
  await click(500, 250);
  await page.locator('#shapeFloorButton').click();
  const converted = (await snapshot()).floors[0].entities.find(e => e.type === 'room');
  assert.equal(converted.outline.length, 6);
  assert.ok((await item('shape')), 'matching floor keeps the existing shape wall');
  assert.equal(await page.evaluate(id => window.__editorTest.floorAt(id, 300, 250), converted.id), true);
  await page.screenshot({ path: `${output}/free-floor.png` });
  console.log('PASS: free floors: concave/circular, 2D and 3D cutouts, vertices, matching shapes, locks, undo and reload');

  const furniture = { id: 'chair', type: 'furniture', kind: 'table', x: 200, y: 160, w: 160, h: 85, rotation: 0 };
  await importPlan(plan([{ ...room, name: '' }, furniture]));
  await page.locator('button[data-view-mode="three"]').click();
  await page.waitForTimeout(400);
  let p = await project(280, 200, .41);
  const before = await item('chair');
  await move(p, 55, 20);
  assert.deepEqual(await item('chair'), before, 'single drag over furniture only rotates the camera');
  await page.locator('button[data-view-mode="split"]').click();
  await page.locator('#fitButton').click();
  await page.locator('button[data-view-mode="three"]').click();
  await page.waitForTimeout(600);
  p = await project(280, 200, .41);
  await page.mouse.dblclick(p.x, p.y);
  assert.equal(await page.locator('#threeMoveToggle').getAttribute('aria-pressed'), 'true');
  await move(p, 70, 30);
  assert.notDeepEqual(await item('chair'), before);
  await page.locator('#undoButton').click();
  assert.deepEqual(await item('chair'), before);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#threeMoveToggle').getAttribute('aria-pressed'), 'false');
  p = await project(280, 200, .41);
  await page.mouse.dblclick(p.x, p.y);
  await page.locator('#entityLockedInput').check();
  assert.equal(await page.locator('#threeMoveToggle').isDisabled(), true);
  assert.equal(await page.locator('#threeMoveToggle').getAttribute('aria-pressed'), 'false');

  const viewKey = 'madori-quick-3d-view-state';
  const floors = plan([{ ...room, name: '' }]);
  floors.floors.push({ id: 'f2', name: '2F', entities: [{ ...room, id: 'upper', name: '' }] }, { id: 'f3', name: '3F', entities: [{ ...room, id: 'top', name: '' }] });
  await importPlan(floors);
  await page.waitForTimeout(600);
  await page.addInitScript(key => {
    if (sessionStorage.getItem('screen-pan-seeded')) return;
    localStorage.setItem(key, JSON.stringify({ camera: { position: [3, 4.35, 6], target: [3, 4.2, 4] } }));
    sessionStorage.setItem('screen-pan-seeded', 'yes');
  }, viewKey);
  await page.reload();
  await page.waitForTimeout(700);
  const pose = () => page.evaluate(() => window.__editorTest.cameraPose());
  const initial = await pose();
  const canvas = await page.locator('#threeCanvas').boundingBox();
  for (let i = 0; i < 3; i++) {
    await page.mouse.move(canvas.x + canvas.width / 2, canvas.y + canvas.height * .3);
    await page.mouse.down({ button: 'right' });
    await page.mouse.move(canvas.x + canvas.width / 2, canvas.y + canvas.height * .8, { steps: 12 });
    await page.mouse.up({ button: 'right' });
    await page.waitForTimeout(600);
  }
  const raised = await pose();
  assert.ok(raised.position[1] > initial.position[1] + 1, `right drag raises the viewpoint above the second floor: ${initial.position[1]} -> ${raised.position[1]}`);
  const direction = camera => { const d = camera.target.map((n, i) => n - camera.position[i]), length = Math.hypot(...d); return d.map(n => n / length); };
  assert.ok(direction(initial).every((n, i) => Math.abs(n - direction(raised)[i]) < .001), 'screen-plane movement keeps the viewing direction');
  console.log('PASS: 3D double-click movement, single-drag orbit, lock, Escape, undo and screen-plane elevation');
  await page.locator('button[data-view-mode="split"]').click();
  await page.locator('#fitButton').click();
  await page.screenshot({ path: `${output}/three-move-and-pan.png` });
}
