import assert from 'node:assert/strict';

export async function verifyRoofShapes({ page, importPlan, choose, planPoint, project, change, move, pixels, output }) {
  const plan = (entities = [], roofs = []) => ({ floors: [{ id: 'f1', name: '1F', entities }], activeFloor: 0, roofs, selectedId: null });
  const snapshot = () => page.evaluate(() => window.__editorTest.snapshot());
  const first = async () => (await snapshot()).roofs[0];
  const click = async (x,y) => { const p = await planPoint(x,y); await page.mouse.click(p.x,p.y); };
  await importPlan(plan([{ id: 'circle', type: 'shape', kind: 'circle', x: 300, y: 300, r: 200, startAngle: 0, endAngle: Math.PI*2 }]));
  await page.locator('button[data-view-mode="split"]').click();
  await click(500,300);
  await choose('[data-roof-add="cone"]');
  let roof = await first();
  assert.equal(roof.kind,'cone'); assert.equal(roof.w,480); assert.equal(roof.h,480);
  assert.deepEqual([roof.x+roof.w/2,roof.y+roof.h/2],[300,300]);
  await change('#roofRiseInput',180);
  let bounds = await page.evaluate(id=>window.__editorTest.bounds(id),roof.id);
  assert.ok(Math.abs(bounds.max[1]-bounds.min[1]-1.88)<1e-5);
  await change('#roofDiameterInput',535);
  roof = await first(); assert.equal(roof.w,535); assert.equal(roof.h,535);
  assert.deepEqual([roof.x+roof.w/2,roof.y+roof.h/2],[300,300]);
  await page.locator('#undoButton').click(); assert.equal((await first()).w,480);
  await page.locator('#redoButton').click(); assert.equal((await first()).w,535);
  await page.locator('#roofKindInput').selectOption('dome');
  await change('#roofRiseInput',''); assert.equal((await first()).rise,undefined);
  await change('#roofWInput',600); await change('#roofHInput',400);
  roof = await first();
  bounds = await page.evaluate(id=>window.__editorTest.bounds(id),roof.id);
  assert.ok(Math.abs(bounds.max[0]-bounds.min[0]-6)<1e-5);
  assert.ok(Math.abs(bounds.max[2]-bounds.min[2]-4)<1e-5);
  assert.equal(await page.evaluate(([x,y])=>window.__editorTest.hit(x,y),[roof.x+60,roof.y+40]),null,'empty bounding-box corners do not hit an ellipse');
  assert.equal(await page.evaluate(([id,x,y])=>window.__editorTest.floorAt(id,x,y),[roof.id,roof.x+60,roof.y+40]),false);
  await page.locator('#roofKindInput').selectOption('polygon');
  await change('#roofSidesInput',5); await change('#roofRotationInput',23); await change('#roofDiameterInput',445);
  roof = await first(); assert.equal(roof.w,445); assert.equal(roof.h,445); assert.equal(roof.sides,5); assert.equal(roof.rotation,23);
  assert.equal(await page.locator('#roofWInput').count(),0);
  await page.locator('#fitButton').click();
  const radius=roof.w/2, a=roof.rotation*Math.PI/180, cx=roof.x+radius, cy=roof.y+radius;
  for (let i=0;i<5;i++) {
    const edgeAngle=a+(i+.5)*Math.PI*2/5, r=radius*(Math.cos(Math.PI/5)+.08);
    assert.equal(await page.evaluate(([id,x,y])=>window.__editorTest.floorAt(id,x,y),[roof.id,cx+Math.cos(edgeAngle)*r,cy+Math.sin(edgeAngle)*r]),false,'3D does not fill outside the polygon');
  }
  await move(await planPoint(roof.x+roof.w,roof.y+roof.h),30,10);
  roof = await first(); assert.equal(roof.w,roof.h,'corner resize preserves regular sides'); assert.ok(roof.w>445);
  await page.locator('#undoButton').click();
  await change('#roofSidesInput',2); assert.equal((await first()).sides,3);
  await change('#roofSidesInput',7);
  await change('#roofRiseInput',210);
  await page.locator('#entityLockedInput').check();
  for (const id of ['roofSidesInput','roofRotationInput','roofDiameterInput','roofRiseInput','roofKindInput']) assert.equal(await page.locator(`#${id}`).isDisabled(),true);
  await page.locator('#entityLockedInput').uncheck();
  const before = await first();
  await page.locator('button[data-view-mode="three"]').click();
  await page.waitForTimeout(200);
  bounds = await page.evaluate(id=>window.__editorTest.bounds(id),before.id);
  const top = await project(before.x+before.w/2,before.y+before.h/2,bounds.max[1]-.3);
  await page.mouse.click(top.x,top.y);
  assert.equal((await snapshot()).selectedId,before.id);
  await page.locator('button[data-view-mode="plan"]').click();
  await page.locator('#fitButton').click();
  await move(await planPoint(before.x+before.w/2,before.y+before.h/2),45,20);
  assert.notDeepEqual([ (await first()).x,(await first()).y ],[before.x,before.y]);
  await page.locator('#undoButton').click();
  assert.deepEqual(await first(),before);
  delete before.locked;
  await page.reload({waitUntil:'domcontentloaded'}); await page.waitForFunction(()=>Boolean(window.__editorTest));
  assert.deepEqual(await first(),before);
  const download = page.waitForEvent('download'); await page.locator('#exportButton').click();
  const chunks=[]; for await(const chunk of await (await download).createReadStream()) chunks.push(chunk);
  await importPlan(JSON.parse(Buffer.concat(chunks).toString())); assert.deepEqual(await first(),before);
  console.log('PASS: cone, dome and regular polygon roofs: matched placement, diameter, ellipse, height, sides, rotation, footprint, locks, 3D selection, movement, undo and JSON reload');

  await importPlan(plan([], [{id:'tall-roof',type:'roof',kind:'cone',x:0,y:0,w:400,h:400,floorId:'f1',rise:2000}]));
  await page.locator('button[data-view-mode="split"]').click();
  await page.locator('#fitButton').click();
  await page.waitForTimeout(300);
  const tallBounds=await page.evaluate(()=>window.__editorTest.bounds('tall-roof'));
  const tip=await project(200,200,tallBounds.max[1]);
  const tallCanvas=await page.locator('#threeCanvas').boundingBox();
  assert.ok(tip.x>tallCanvas.x && tip.x<tallCanvas.x+tallCanvas.width && tip.y>tallCanvas.y+100 && tip.y<tallCanvas.y+tallCanvas.height,'fit includes tall roof tips below the toolbar');

  const gallery = ['cone','dome','polygon'].map((kind,i)=>({id:`roof-${i}`,type:'roof',kind,x:i*760,y:0,w:600,h:600,floorId:'f1',sides:7,rotation:15}));
  await importPlan(plan(gallery.map((r,i)=>({id:`wall-${i}`,type:'shape',kind:i===2?'polygon':'circle',x:r.x+300,y:300,r:260,startAngle:0,endAngle:Math.PI*2,sides:7,rotation:Math.PI/12})),gallery));
  await page.locator('button[data-view-mode="split"]').click();
  await page.locator('#fitButton').click();
  assert.ok((await pixels()).colors>20);
  await page.screenshot({path:`${output}/roof-shapes-desktop.png`});
  const hash=(await pixels()).hash, box=await page.locator('#threeCanvas').boundingBox();
  await move({x:box.x+box.width*.85,y:box.y+box.height*.25},70,35);
  assert.notEqual((await pixels()).hash,hash,'roofs remain interactive in 3D');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#fitButton').click();
  await page.locator('button[data-view-mode="three"]').click();
  await page.locator('#panelToggle').click();
  assert.ok((await pixels()).colors>20);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:`${output}/roof-shapes-mobile.png`});
  console.log('PASS: round and polygon roof gallery on desktop/mobile, matching 2D footprints, nonblank canvas and orbit');
}
