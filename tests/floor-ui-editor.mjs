import assert from 'node:assert/strict';

export async function verifyFloorUi({ page, importPlan, planPoint, move, change, output, pixels }) {
  const base = { id: 'base', type: 'room', name: '', x: 0, y: 0, w: 600, h: 600, color: '#ffffff' };
  const plan = entities => ({ floors: [{ id: 'f1', name: '1F', entities }], activeFloor: 0, selectedId: null, roofs: [] });
  const snapshot = () => page.evaluate(() => window.__editorTest.snapshot());
  const items = async () => (await snapshot()).floors[0].entities;
  const item = async id => (await items()).find(e => e.id === id);
  const click = async (x, y) => { const p = await planPoint(x, y); await page.mouse.click(p.x, p.y); };
  const start = async () => { await page.locator('[data-tool="floor"]').click(); };
  const l = [[80,80],[520,80],[520,280],[300,280],[300,520],[80,520]];
  await page.locator('button[data-view-mode="split"]').click();
  await importPlan(plan([base]));
  await start();
  await page.locator('#draftSurfacePicker [data-surface-choice="wood"]').click();
  for (const p of l.slice(0, 3)) await click(...p);
  await page.locator('#floorDraftUndo').click();
  assert.match(await page.locator('#floorToolbar').textContent(), /2点/);
  await click(...l[2]);
  await page.keyboard.press('Control+z');
  assert.match(await page.locator('#floorToolbar').textContent(), /2点/);
  await page.keyboard.press('Control+Shift+z');
  assert.match(await page.locator('#floorToolbar').textContent(), /3点/);
  await page.locator('#undoButton').click();
  await page.locator('#redoButton').click();
  assert.match(await page.locator('#floorToolbar').textContent(), /3点/);
  await page.locator('#floorDraftUndo').click();
  for (const p of l.slice(2)) await click(...p);
  await page.screenshot({ path: `${output}/floor-drawing-desktop.png` });
  await click(...l[0]);
  let floor = (await items()).find(e => e.id !== 'base');
  assert.equal(floor.outline.length, 6); assert.equal(floor.name, ''); assert.equal(floor.surface, 'wood');
  assert.equal(await page.evaluate(id => window.__editorTest.floorAt(id, 450, 450), floor.id), false);
  assert.equal(await page.evaluate(id => window.__editorTest.floorAt(id, 150, 450), floor.id), true);
  await page.locator('#undoButton').click(); assert.equal((await items()).length, 1);
  await page.locator('#redoButton').click(); assert.equal((await items()).length, 2);
  await page.reload(); await page.waitForFunction(() => Boolean(window.__editorTest));
  assert.equal((await item(floor.id)).outline.length, 6);
  await start(); await click(120,120); await click(220,120); await page.keyboard.press('Escape');
  assert.equal((await items()).length, 2); assert.equal(await page.locator('#floorToolbar').isVisible(), false);
  await start();
  for (const p of [[80,80],[520,520],[80,520],[520,80]]) await click(...p);
  await page.locator('#floorDraftFinish').click();
  assert.equal((await items()).length, 2);
  assert.match(await page.locator('.floor-error').textContent(), /交差/);
  await page.locator('#floorDraftCancel').click();
  await start(); await click(100,100); await click(200,100); await click(200,200); await page.keyboard.press('Enter');
  assert.equal((await items()).length, 3);
  await start(); await click(100,100);
  const pan = await planPoint(300,300);
  await page.mouse.move(pan.x,pan.y); await page.mouse.down({button:'right'});
  await page.mouse.move(pan.x+20,pan.y+10); await page.mouse.up({button:'right'});
  assert.match(await page.locator('#floorToolbar').textContent(), /1点/);
  await page.keyboard.down('Shift'); await click(300,140); await page.keyboard.up('Shift');
  await click(300,300); await page.keyboard.press('Enter');
  const constrained = (await items()).at(-1);
  assert.equal(constrained.outline[0][1],constrained.outline[1][1], 'Shift constrains the segment horizontally');
  console.log('PASS: click-to-draw floors, start-point/Enter closure, material, preview, concavity in 3D, draft undo/cancel, invalid paths, one-step history and reload');

  await importPlan(plan([{ ...base, w: 600, h: 400 }]));
  await page.locator('[data-tool="select"]').click(); await click(100,100);
  await page.locator('[data-floor-preset="l"]').click();
  const before = await item('base');
  await move(await planPoint(600, 400), 20, 10);
  assert.deepEqual((await item('base')).outline, before.outline, 'normal selection scales the whole outline');
  await page.locator('#undoButton').click();
  await page.locator('#floorEditToggle').click();
  await click(300,200);
  assert.match(await page.locator('.vertex-heading').textContent(), /頂点 4/);
  await change('#floorVertexX', 260);
  assert.equal(await page.locator('#floorVertexX').inputValue(), '260', 'active vertex persists after changing coordinates');
  assert.match(await page.locator('.vertex-heading').textContent(), /頂点 4/);
  await page.locator('#floorVertexAdd').click();
  assert.equal((await item('base')).outline.length, 7);
  await page.locator('#floorVertexRemove').click();
  assert.equal((await item('base')).outline.length, 6);
  await click(300,0);
  assert.equal((await item('base')).outline.length, 7, 'edge midpoint click adds a vertex');
  await page.keyboard.press('Delete'); assert.equal((await item('base')).outline.length, 6);
  await page.screenshot({ path: `${output}/floor-outline-desktop.png` });
  await page.locator('#floorEditDone').click();
  await page.locator('#entityLockedInput').check();
  assert.equal(await page.locator('#floorEditToggle').isDisabled(), true);
  assert.equal(await page.locator('[data-floor-preset="circle"]').isDisabled(), true);
  await importPlan(plan([{ ...base, holes: [[[.7,.7],[.9,.7],[.9,.9],[.7,.9]]] }]));
  await click(100,100); await page.locator('[data-floor-preset="l"]').click();
  assert.equal((await item('base')).outline, undefined, 'invalid preset cannot destroy a stairwell');
  assert.equal((await item('base')).holes.length, 1);
  assert.match(await page.locator('.floor-error').textContent(), /開口/);
  console.log('PASS: whole-floor resize versus contour edit, persistent vertex, edge insertion, deletion, locks and stairwell protection');

  const circle = { id: 'circle', type: 'shape', kind: 'circle', x: 300, y: 300, r: 200, startAngle: 0, endAngle: Math.PI*2 };
  await importPlan(plan([circle])); await click(500,300);
  const origin = await item('circle');
  await move(await planPoint(500,300), 40,0);
  let enlarged = await item('circle');
  assert.ok(enlarged.r > 200); assert.equal(enlarged.x,300); assert.equal(enlarged.y,300);
  await page.locator('#undoButton').click(); assert.deepEqual(await item('circle'),origin);
  await move(await planPoint(500,300), 40,0,true); assert.deepEqual(await item('circle'),origin);
  await change('#shapeDiameterInput', 525); assert.equal((await item('circle')).r,262.5);
  await page.locator('#shapeDiameterPlus').click(); assert.equal((await item('circle')).r,267.5);
  await page.locator('#shapeDiameterInput').fill('605');
  await page.locator('#shapeDiameterPlus').click();
  assert.equal((await item('circle')).r,307.5, 'blur must not swallow the following plus click');
  const slider = page.locator('#shapeDiameterRange');
  await slider.focus();
  await page.keyboard.press('ArrowRight');
  const firstKey = (await item('circle')).r;
  await page.keyboard.press('ArrowRight');
  assert.equal((await item('circle')).r,firstKey+5, 'slider keeps keyboard focus between changes');
  const previous = await item('circle');
  const bounds = await slider.boundingBox();
  await move({ x: bounds.x + bounds.width*.3, y: bounds.y + bounds.height/2 }, bounds.width*.25,0);
  assert.notEqual((await item('circle')).r,previous.r);
  await page.locator('#undoButton').click(); assert.deepEqual(await item('circle'),previous, 'one slider gesture is one undo step');
  await page.locator('#entityLockedInput').check();
  assert.equal(await page.locator('#shapeDiameterRange').isDisabled(),true);
  await page.locator('#entityLockedInput').uncheck();
  await page.locator('#shapeKindInput').selectOption('arc');
  await page.locator('#fitButton').click();
  const arc = await item('circle');
  await move(await planPoint(arc.x+arc.r,arc.y), -20,0);
  assert.ok((await item('circle')).r<arc.r);
  assert.equal((await item('circle')).startAngle,arc.startAngle);
  await page.locator('#shapeKindInput').selectOption('circle');
  await page.locator('#shapeFloorButton').click();
  floor = (await items()).find(e=>e.type==='room');
  assert.equal(await page.locator('#floorDiameterInput').isVisible(),true);
  const center = [floor.x+floor.w/2,floor.y+floor.h/2];
  await change('#floorDiameterInput',600);
  floor = await item(floor.id); assert.equal(floor.w,600); assert.equal(floor.h,600);
  assert.deepEqual([floor.x+floor.w/2,floor.y+floor.h/2],center);
  await page.locator('#fitButton').click();
  await move(await planPoint(floor.x+floor.w,floor.y+floor.h/2), -30,0);
  const resized = await item(floor.id); assert.ok(resized.w<600); assert.equal(resized.w,resized.h);
  assert.equal(resized.outline.length,64);
  await page.locator('#fitButton').click();
  assert.ok((await pixels()).colors>15);
  await page.screenshot({ path: `${output}/circle-size-desktop.png` });
  await page.reload(); await page.waitForFunction(()=>Boolean(window.__editorTest));
  assert.equal((await item(floor.id)).w,resized.w);
  console.log('PASS: circle wall and floor handles, centered resizing, exact diameter, live slider, one-step undo, Escape, locks, 3D and reload');

  await page.setViewportSize({width:390,height:844});
  await page.locator('button[data-view-mode="plan"]').click();
  await start();
  await page.locator('#panelToggle').click();
  await page.locator('#fitButton').click();
  const box = await page.locator('#planCanvas').boundingBox();
  for (const [x,y] of [[.2,.35],[.8,.35],[.6,.7],[.2,.7]]) await page.mouse.click(box.x+box.width*x,box.y+box.height*y);
  await page.screenshot({path:`${output}/floor-drawing-mobile.png`});
  const prior = (await items()).length;
  await page.locator('#floorDraftFinish').click(); assert.equal((await items()).length,prior+1);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('button[data-view-mode="three"]').click();
  assert.ok((await pixels()).colors>15);
  await page.screenshot({path:`${output}/floor-mobile-3d.png`});
  await page.locator('#panelToggle').click();
  await page.setViewportSize({width:1440,height:1000});
  await page.locator('button[data-view-mode="split"]').click();
  await page.locator('[data-tool="select"]').click();
  console.log('PASS: floor drawing toolbar with collapsed sidebar on mobile, responsive layout and nonblank 3D');

  const touch = await page.context().browser().newContext({ viewport: {width:390,height:844}, isMobile:true, hasTouch:true });
  try {
    const mobile = await touch.newPage();
    const errors = []; mobile.on('pageerror', error=>errors.push(error.message));
    await mobile.goto(page.url(),{waitUntil:'domcontentloaded'});
    await mobile.waitForFunction(()=>Boolean(window.__editorTest));
    await mobile.locator('#importInput').setInputFiles({name:'touch.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(plan([base])))});
    await mobile.waitForTimeout(200);
    await mobile.locator('button[data-view-mode="plan"]').tap();
    await mobile.locator('[data-tool="floor"]').tap();
    await mobile.locator('#panelToggle').tap();
    await mobile.locator('#fitButton').tap();
    const canvas = await mobile.locator('#planCanvas').boundingBox();
    for (const [x,y] of [[.2,.35],[.8,.35],[.8,.7],[.2,.7]]) await mobile.touchscreen.tap(canvas.x+canvas.width*x,canvas.y+canvas.height*y);
    await mobile.locator('#floorDraftFinish').tap();
    assert.equal(await mobile.evaluate(()=>window.__editorTest.snapshot().floors[0].entities.length),2);
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    const bar = await mobile.locator('.pane-bar').boundingBox(), toolbar = await mobile.locator('#floorToolbar').boundingBox();
    assert.ok(toolbar.y>=bar.y+bar.height, 'floor edit toolbar must not cover the floor tabs');
    await mobile.screenshot({path:`${output}/floor-touch.png`});
    assert.deepEqual(errors,[]);
  } finally { await touch.close(); }
  console.log('PASS: touch-created floor and unobstructed floor tabs on a phone');
}
